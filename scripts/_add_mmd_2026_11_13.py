for fname, diagram in DIAGRAMS.items():
    p = PROJ / fname
    if not p.exists():
        print(f"{fname}: MISSING")
        continue
    c = p.read_text(encoding="utf-8")
    if "## 架构图（MMD）" in c:
        print(f"{fname}: already has diagram -- skipped")
        continue
    marker = "\n## 定位判断\n"
    if marker not in c:
        print(f"{fname}: 定位判断 marker not found")
        continue
    block = HEADER + diagram + FOOTER
    c = c.replace(marker, "\n" + block + marker, 1)
    p.write_text(c, encoding="utf-8")
    print(f"{fname}: diagram inserted ({len(block)} bytes)")
