#!/usr/bin/env python3
"""CALIBER-CONTROLLED skill-identity measurement for 2026-11-22.

The 11-18 daily report measured "independent skill identity" as the count of
distinct PARENT-DIRECTORY NAMES.  The 11-22 probe measured identity as the
count of distinct (parent-dir -> blob-sha-set) tuples.  Those two calibers
give different numbers on identical trees.

This script measures BOTH calibers, plus a third (distinct blob sha), on the
same tree fetched once, for every skill-bearing repo on today's trending list,
and compares against the numbers recorded in the 11-18 daily report.

Question being answered:
  Q1. Did skill replication actually change between 11-18 and 11-22, or is
      the change an artifact of the identity definition?
  Q2. Under a content-identity caliber (distinct blob sha), what is the
      true replication factor of each skill repo?
  Q3. Is the copy set generated by CI (i.e. identical shas) or forked by hand
      (divergent shas)?

Output: /tmp/caliber_1122.json
"""
import json
import os
import subprocess
import sys
import urllib.parse
from collections import Counter, defaultdict

ENV = dict(os.environ, HOME="/home/lohasle")
OUT = "/tmp/caliber_1122.json"


def api(path, params=None, raw=False, headers=None, timeout=120):
    url = path
    if params:
        url = path + "?" + urllib.parse.urlencode(params, quote_via=urllib.parse.quote)
    cmd = ["gh", "api"]
    for h in (headers or []):
        cmd += ["-H", h]
    cmd.append(url)
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, env=ENV, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None
    if p.returncode != 0:
        return None
    if raw:
        return p.stdout
    try:
        return json.loads(p.stdout)
    except Exception:  # noqa: BLE001
        return None


def measure(full):
    m = api(f"repos/{full}") or {}
    branch = m.get("default_branch") or "main"
    tree = api(f"repos/{full}/git/trees/{branch}?recursive=1") or {}
    blobs = [b for b in (tree.get("tree") or []) if b.get("type") == "blob"]
    skills = [b for b in blobs
              if os.path.basename(b.get("path") or "").lower() == "skill.md"]
    if not skills:
        return {"repo": full, "n_skill_files": 0}

    # Caliber A (11-18 report): identity = parent directory NAME
    name_ident = defaultdict(list)
    for b in skills:
        p = b.get("path") or ""
        parent = os.path.basename(os.path.dirname(p)) if "/" in p else "<root>"
        name_ident[parent].append(b)
    n_name_ident = len(name_ident)

    # Caliber B (11-22 probe): identity = (parent dir -> frozenset of blob shas)
    shaset_ident = defaultdict(set)
    for b in skills:
        p = b.get("path") or ""
        parent = p.rsplit("/", 1)[0] if "/" in p else "<root>"
        shaset_ident[parent].add(b.get("sha"))
    n_shaset_ident = len({frozenset(v) for v in shaset_ident.values()})

    # Caliber C: pure content identity = distinct blob sha
    sha_counter = Counter(b.get("sha") for b in skills)
    n_distinct_sha = len(sha_counter)
    dup_groups = {s: c for s, c in sha_counter.items() if c > 1}
    max_copies = max(sha_counter.values()) if sha_counter else 0

    # replica detail under caliber A: names appearing in >1 directory
    name_dir_count = Counter()
    for b in skills:
        p = b.get("path") or ""
        parent = os.path.basename(os.path.dirname(p)) if "/" in p else "<root>"
        name_dir_count[parent] += 1
    replicated_names = {n: c for n, c in name_dir_count.items() if c > 1}
    replica_files = sum(replicated_names.values())
    replica_dirs = len(replicated_names)

    # per-name directory listing, to see whether the copies are byte-identical
    per_name = defaultdict(list)
    for b in skills:
        p = b.get("path") or ""
        parent = os.path.basename(os.path.dirname(p)) if "/" in p else "<root>"
        per_name[parent].append({"path": p, "sha": b.get("sha"),
                                 "size": b.get("size")})

    # how many replicated names have IDENTICAL sha everywhere (CI-generated)
    # vs DIVERGENT sha (hand-forked / adapted)
    identical_copy_names, divergent_copy_names = [], []
    for n, lst in per_name.items():
        if len(lst) < 2:
            continue
        shas = {x["sha"] for x in lst}
        (identical_copy_names if len(shas) == 1 else divergent_copy_names).append(
            {"name": n, "copies": len(lst), "distinct_sha": len(shas)})

    # CI evidence: is there a workflow/script that generates the copies?
    wf = api(f"repos/{full}/contents/.github/workflows") or []
    wf_names = [w.get("name") for w in wf] if isinstance(wf, list) else []

    return {
        "repo": full,
        "stars": m.get("stargazers_count"),
        "forks": m.get("forks_count"),
        "subs": m.get("subscribers_count"),
        "open_issues": m.get("open_issues_count"),
        "size_kb": m.get("size"),
        "language": m.get("language"),
        "license": (m.get("license") or {}).get("spdx_id"),
        "created_at": m.get("created_at"),
        "pushed_at": m.get("pushed_at"),
        "n_blobs": len(blobs),
        "truncated_tree": tree.get("truncated"),
        "n_skill_files": len(skills),
        "calA_name_ident": n_name_ident,
        "calB_shaset_ident": n_shaset_ident,
        "calC_distinct_sha": n_distinct_sha,
        "repl_A": round(len(skills) / n_name_ident, 2) if n_name_ident else 0,
        "repl_C": round(len(skills) / n_distinct_sha, 2) if n_distinct_sha else 0,
        "replicated_names": len(replicated_names),
        "replica_files": replica_files,
        "replica_file_pct": round(100.0 * replica_files / len(skills), 1) if skills else 0,
        "max_copies": max_copies,
        "n_dup_sha_groups": len(dup_groups),
        "identical_copy_names": identical_copy_names,
        "divergent_copy_names": divergent_copy_names,
        "n_identical_copy_names": len(identical_copy_names),
        "n_divergent_copy_names": len(divergent_copy_names),
        "workflows": wf_names,
        "top_replicated": sorted(replicated_names.items(), key=lambda x: -x[1])[:12],
    }


def main():
    trend = json.load(open("/tmp/trend_1122.json"))
    items = [t["full_name"] for t in trend]
    out = []
    for i, r in enumerate(items, 1):
        res = measure(r)
        if res and res.get("n_skill_files"):
            out.append(res)
            print(f"[{i}/{len(items)}] {r:42s} files={res['n_skill_files']:4d} "
                  f"calA={res['calA_name_ident']:4d} calB={res['calB_shaset_ident']:4d} "
                  f"calC(sha)={res['calC_distinct_sha']:4d} "
                  f"replA={res['repl_A']:.2f} replC={res['repl_C']:.2f} "
                  f"ident_copy_names={res['n_identical_copy_names']} "
                  f"divergent={res['n_divergent_copy_names']}", flush=True)
    json.dump(out, open(OUT, "w"), ensure_ascii=False, indent=1)
    print(f"wrote {len(out)} -> {OUT}")


if __name__ == "__main__":
    main()
